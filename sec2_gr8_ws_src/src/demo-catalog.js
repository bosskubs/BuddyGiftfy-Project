export async function seedDemoCatalog() {
  return transaction(async (connection) => {
    let added = 0;
    for (const [
      sku,
      slug,
      name,
      description,
      category,
      image,
      price,
      stock,
      featured,
      previousImage,
    ] of demoProducts) {
      await connection.execute(
        "INSERT IGNORE INTO categories(name,is_custom) VALUES(?,?)",
        [category, Number(category === "ของขวัญสั่งทำ")],
      );
      const [result] = await connection.execute(
        `INSERT IGNORE INTO products (sku,slug,name,description,category,image_url,price,stock_quantity,status,is_featured)
         VALUES (?,?,?,?,?,?,?,?,?,?)`,
        [
          sku,
          slug,
          name,
          description,
          category,
          image,
          price,
          stock,
          stock > 0 ? "Available" : "Out of stock",
          featured,
        ],
      );
      added += result.affectedRows;
      // Refresh only the original demo artwork, leaving custom images intact.
      if (previousImage) {
        await connection.execute(
          "UPDATE products SET image_url = ? WHERE sku = ? AND slug = ? AND image_url = ?",
          [image, sku, slug, previousImage],
        );
      }
    }
    return added;
  });
}
